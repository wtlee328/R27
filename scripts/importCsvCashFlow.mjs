function parseCsv(csvText) {
  const lines = csvText.trim().split('\n')
  const headers = lines[0].split(',')
  const rows = []
  
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim()
    if (!line) continue
    
    // Split line taking quotes into account
    const cols = []
    let current = ''
    let inQuotes = false
    
    for (let j = 0; j < line.length; j++) {
      const char = line[j]
      if (char === '"') {
        inQuotes = !inQuotes
      } else if (char === ',' && !inQuotes) {
        cols.push(current)
        current = ''
      } else {
        current += char
      }
    }
    cols.push(current)
    
    const [dateStr, category, rawAmount, description, notes] = cols
    
    // Clean amount (remove $ and commas)
    const amountNum = parseFloat(rawAmount.replace(/[\$,]/g, '')) || 0
    
    // Determine type (income vs expense)
    let type = 'expense'
    if (category === '公司存款' || category === '預收款') {
      type = 'income'
    } else if (category === '課程收入' && (description.includes('退款') || description.includes('退費'))) {
      type = 'expense'
    }
    
    // Parse date
    const [y, m, d] = dateStr.split('-').map(Number)
    const dateObj = new Date(Date.UTC(y, m - 1, d, 0, 0, 0))
    
    rows.push({
      dateStr,
      dateObj,
      category,
      amount: amountNum,
      description: description || '',
      notes: notes || '',
      type,
      account: '公司存款'
    })
  }
  
  return rows
}

async function importRecords() {
  const parsedRows = parseCsv(CSV_DATA)
  console.log(`Parsed ${parsedRows.length} CSV records total.`)
  
  let successCount = 0
  const batchSize = 100
  let batch = db.batch()
  let countInBatch = 0

  for (const r of parsedRows) {
    const docRef = db.collection('cashFlowRecords').doc()
    
    const docData = {
      centerId: 'r27',
      trainerId: 'system',
      date: Timestamp.fromDate(r.dateObj),
      type: r.type,
      category: r.category,
      amount: r.amount,
      account: r.account, // 公司存款
      description: r.description,
      notes: r.notes,
      source: 'csv_import',
      sourceId: null,
      createdAt: FieldValue.serverTimestamp(),
      updatedAt: FieldValue.serverTimestamp(),
    }

    batch.set(docRef, docData)
    countInBatch++
    successCount++

    if (countInBatch >= batchSize) {
      await batch.commit()
      console.log(`Committed batch of ${countInBatch} records...`)
      batch = db.batch()
      countInBatch = 0
    }
  }

  if (countInBatch > 0) {
    await batch.commit()
    console.log(`Committed final batch of ${countInBatch} records.`)
  }

  console.log(`\n✅ Success! Successfully imported ${successCount} cash flow records into Firestore.`)
  process.exit(0)
}

importRecords().catch(err => {
  console.error('Import failed:', err)
  process.exit(1)
})
